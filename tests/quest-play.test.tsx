// @vitest-environment jsdom
import { cleanup, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, expect, it, vi } from 'vitest'
import QuestPlayPage from '../src/QuestPlayPage'
import { newQuestState, updateQuestProgress } from '../src/lib/questProgress'
import { setSyncAccount } from '../src/lib/accountSync'
afterEach(()=>{cleanup();localStorage.clear();setSyncAccount(null);vi.restoreAllMocks()})
function start(){setSyncAccount(null);localStorage.setItem('dana-quest-progress-v2',JSON.stringify(updateQuestProgress(updateQuestProgress(newQuestState(),{type:'start',questId:'due-dau-an-50-nam'}),{type:'confirm-arrival',questId:'due-dau-an-50-nam'})))}
it('separates story, challenge and saved feedback; wrong answers preserve input and do not advance',async()=>{
 start();const user=userEvent.setup();render(<QuestPlayPage id="due-dau-an-50-nam"/> )
 expect(screen.queryByRole('textbox')).toBeNull()
 await user.click(await screen.findByRole('button',{name:'Tiếp tục đến thử thách'}))
 await user.type(screen.getByRole('textbox'), '72')
 await user.click(screen.getByRole('button',{name:'Kiểm tra đáp án'}))
 expect(await screen.findByRole('alert')).toBeTruthy();expect(screen.getByRole('textbox')).toHaveProperty('value','72')
 await user.clear(screen.getByRole('textbox'));await user.type(screen.getByRole('textbox'),'71')
 await user.click(screen.getByRole('button',{name:'Kiểm tra đáp án'}))
 await screen.findByRole('heading',{name:'Bạn đã giải đúng!'})
 expect(JSON.parse(localStorage.getItem('dana-quest-progress-v2')!).quests['due-dau-an-50-nam'].completedCheckpointIds).toEqual(['cong-71'])
 await user.click(screen.getByRole('button',{name:'Tiếp tục câu chuyện'}))
 await user.click(screen.getByRole('button',{name:'Tiếp tục đến thử thách'}))
 await user.click(screen.getByRole('radio',{name:'Năm 1975'}))
 await user.click(screen.getByRole('button',{name:'Kiểm tra đáp án'}))
 await user.click(await screen.findByRole('button',{name:'Tiếp tục câu chuyện'}));await user.click(screen.getByRole('button',{name:'Tiếp tục đến thử thách'}))
 for(const year of ['1975','2000','2015','2025'])await user.click(screen.getByRole('button',{name:`Thêm ${year}`,exact:true}))
 await user.click(screen.getByRole('button',{name:'Kiểm tra đáp án'}));await user.click(await screen.findByRole('button',{name:'Tiếp tục câu chuyện'}));await user.click(screen.getByRole('button',{name:'Tiếp tục đến thử thách'}))
 for(const [year,choice] of [['2000','25'],['2025','50'],['1975','0'],['2015','40']])await user.selectOptions(screen.getByLabelText(`Năm ${year}`,{exact:true}),choice)
 await user.click(screen.getByRole('button',{name:'Kiểm tra đáp án'}));await user.click(await screen.findByRole('button',{name:'Tiếp tục câu chuyện'}));await user.click(screen.getByRole('button',{name:'Tiếp tục đến thử thách'}))
 for(const label of ['Địa chỉ xuất phát có số nhà 71.','Mốc khởi đầu trong câu chuyện là 1975.','Năm 2000 cách mốc khởi đầu 25 năm.','Năm 2015 cách mốc khởi đầu 40 năm.','Năm 2025 cách mốc khởi đầu 50 năm.'])await user.click(screen.getByRole('checkbox',{name:label,exact:true}))
 await user.click(screen.getByRole('button',{name:'Kiểm tra đáp án'}))
 await user.click(await screen.findByRole('button',{name:'Xem tổng kết'}))
 await screen.findByRole('heading',{name:'Hành trình đã hoàn thành'})
 expect(screen.getAllByText('400 XP').length).toBeGreaterThan(0)
},15000)
it('pauses without deleting progress and has no skip or answer-reveal action',async()=>{
 start();const user=userEvent.setup();render(<QuestPlayPage id="due-dau-an-50-nam"/> )
 await user.click(screen.getByRole('button',{name:'Mở menu quest'}))
 await user.click(screen.getByRole('button',{name:'Tạm dừng quest'}))
 await screen.findByRole('heading',{name:'Hành trình đang tạm dừng'})
 await user.click(screen.getByRole('button',{name:'Tiếp tục quest'}))
 await waitFor(()=>expect(screen.queryByRole('heading',{name:'Hành trình đang tạm dừng'})).toBeNull())
 await user.click(screen.getByRole('button',{name:'Mở trợ giúp'}))
 expect(screen.queryByRole('button',{name:/Bỏ qua|Xem đáp án/})).toBeNull()
 expect(screen.getByRole('heading',{name:'Trợ giúp thử thách'})).toBeTruthy()
})
it('offers searchable FAQ, contextual hint confirmation and back-to-story without clearing the answer',async()=>{
 start();const user=userEvent.setup();render(<QuestPlayPage id="due-dau-an-50-nam"/> )
 await user.click(await screen.findByRole('button',{name:'Tiếp tục đến thử thách'}))
 await user.type(screen.getByRole('textbox'),'72')
 await user.click(screen.getByRole('button',{name:'Đọc lại câu chuyện hiện tại'}))
 expect(screen.getByRole('dialog',{name:'Câu chuyện hiện tại'})).toBeTruthy()
 await user.click(screen.getByRole('button',{name:'Đóng bảng'}))
 expect(screen.getByRole('textbox')).toHaveProperty('value','72')
 await user.click(screen.getByRole('button',{name:'Trợ giúp',exact:true}))
 await user.click(screen.getByRole('button',{name:'Xem gợi ý quan sát'}))
 expect(screen.getByRole('heading',{name:'Mở gợi ý này?'})).toBeTruthy()
 await user.click(screen.getByRole('button',{name:'Đọc gợi ý'}))
 expect(screen.getByText(/Tìm số nhà trong địa chỉ/)).toBeTruthy()
 await user.click(screen.getByRole('button',{name:'Đóng bảng'}))
 await user.click(screen.getByRole('button',{name:'Mở trợ giúp'}))
 await user.click(screen.getByRole('button',{name:/Câu hỏi thường gặp/}))
 await user.type(screen.getByRole('searchbox'),'GPS')
 expect(screen.getByText('GPS không hoạt động thì làm sao?')).toBeTruthy()
 expect(screen.queryByText('Tôi có bị giới hạn thời gian không?')).toBeNull()
})

it('lets an unarrived deep link reach the starting point without an invisible guard',async()=>{
 setSyncAccount(null);localStorage.setItem('dana-quest-progress-v2',JSON.stringify(updateQuestProgress(newQuestState(),{type:'start',questId:'due-dau-an-50-nam'})))
 render(<QuestPlayPage id="due-dau-an-50-nam"/> )
 const link=await screen.findByRole('link',{name:'Tìm điểm bắt đầu'})
 expect(link.getAttribute('href')).toBe('#/quest/due-dau-an-50-nam/chi-duong')
 const request=new CustomEvent('dana-before-navigation',{cancelable:true,detail:{hash:link.getAttribute('href')}})
 window.dispatchEvent(request);expect(request.defaultPrevented).toBe(false)
 expect(screen.queryByRole('button',{name:'Tiếp tục đến thử thách'})).toBeNull()
})
