// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { LoginBackdrop } from '../src/WelcomePage'

afterEach(() => { cleanup(); vi.useRealTimers(); vi.unstubAllGlobals() })
it('shows the official logo and loops five loaded scenery photos every 20 seconds', () => {
  vi.useFakeTimers()
  const view = render(<LoginBackdrop />)
  expect(view.container.querySelector('.login-logo-slot img')?.getAttribute('src')).toContain('/brand/dana-quest-logo.png')
  expect(view.container.querySelector('.login-brand svg')).toBeNull()
  const images = [...view.container.querySelectorAll('.login-landing-photo')]
  expect(images).toHaveLength(5)
  images.forEach(image => fireEvent.load(image))
  const active = () => view.container.querySelector('.login-landing-photo.is-active')?.getAttribute('src')
  expect(active()).toContain('cong-vien-apec')
  act(() => vi.advanceTimersByTime(19999))
  expect(active()).toContain('cong-vien-apec')
  act(() => vi.advanceTimersByTime(1))
  expect(active()).toContain('cau-rong')
  act(() => vi.advanceTimersByTime(20000))
  expect(active()).toContain('cau-song-han')
  act(() => vi.advanceTimersByTime(60000))
  expect(active()).toContain('cong-vien-apec')
  fireEvent.click(screen.getByRole('button', { name: 'Tạm dừng ảnh nền' }))
  act(() => vi.advanceTimersByTime(20000))
  expect(active()).toContain('cong-vien-apec')
  fireEvent.click(screen.getByRole('button', { name: 'Tiếp tục ảnh nền' }))
  act(() => vi.advanceTimersByTime(20000))
  expect(active()).toContain('cau-rong')
})
it('skips a failed photo and keeps the current photo if the next has not loaded', () => {
  vi.useFakeTimers()
  const view = render(<LoginBackdrop />)
  const images = [...view.container.querySelectorAll('.login-landing-photo')]
  fireEvent.load(images[0]); fireEvent.error(images[1])
  act(() => vi.advanceTimersByTime(20000))
  expect(view.container.querySelector('.is-active')?.getAttribute('src')).toContain('cong-vien-apec')
  fireEvent.load(images[2])
  act(() => vi.advanceTimersByTime(20000))
  expect(view.container.querySelector('.is-active')?.getAttribute('src')).toContain('cau-song-han')
})
it('stops autoplay for reduced motion and while the tab is hidden', () => {
  vi.useFakeTimers()
  vi.stubGlobal('matchMedia', () => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() }))
  const reduced = render(<LoginBackdrop />)
  reduced.container.querySelectorAll('img').forEach(image => fireEvent.load(image))
  act(() => vi.advanceTimersByTime(100000))
  expect(reduced.container.querySelector('.is-active')?.getAttribute('src')).toContain('cong-vien-apec')
  expect(screen.queryByRole('button', { name: 'Tạm dừng ảnh nền' })).toBeNull()
  reduced.unmount()
  vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() }))
  const view = render(<LoginBackdrop />)
  view.container.querySelectorAll('img').forEach(image => fireEvent.load(image))
  const visibility = vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('hidden')
  fireEvent(document, new Event('visibilitychange'))
  act(() => vi.advanceTimersByTime(100000))
  expect(view.container.querySelector('.is-active')?.getAttribute('src')).toContain('cong-vien-apec')
  visibility.mockRestore()
})
